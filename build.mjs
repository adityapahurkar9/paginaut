// Frontend build: bundles src/ into dist/ with esbuild.
//   node build.mjs          development build
//   node build.mjs --prod   minified release build
//   node build.mjs --watch  rebuild on change
//   --mobile                the Android viewer (src/mobile) into dist-mobile/ instead
import * as esbuild from "esbuild";
import fs from "node:fs";

const prod = process.argv.includes("--prod");
const watch = process.argv.includes("--watch");
const mobile = process.argv.includes("--mobile");
const outdir = mobile ? "dist-mobile" : "dist";

/**
 * The page viewer's and Read/Book modes' rules, taken from the desktop stylesheet so both apps
 * draw documents the same way: every top-level rule whose selectors all start with one of these.
 */
const READING = [".viewer", ".pg", ".mark-", ".night ", ".rf", ".paper-"];
function readingCss() {
  const css = fs.readFileSync("src/styles.css", "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  const out = [];
  let depth = 0, start = 0;
  for (let i = 0; i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}" && --depth === 0) {
      const rule = css.slice(start, i + 1).trim();
      start = i + 1;
      const sel = rule.slice(0, rule.indexOf("{")).trim();
      if (sel.startsWith("@")) continue;
      if (sel.split(",").every((s) => READING.some((p) => s.trim().startsWith(p)))) out.push(rule);
    }
  }
  return `/* Generated by build.mjs from src/styles.css: the page viewer and Read/Book modes. */\n${out.join("\n")}\n`;
}

/** Oldest browser engine the build runs on: phones' WebViews can lag far behind. */
const TARGET = mobile ? "chrome79" : "chrome120";
/** CSS for older WebViews (e.g. `inset`, which Chrome only knows from 87, as top/right/bottom/left). */
const lowerCss = (css) => esbuild.transformSync(css, { loader: "css", target: TARGET }).code;

fs.mkdirSync(outdir, { recursive: true });
const copyStatic = () => {
  if (mobile) {
    fs.copyFileSync("src/mobile/index.html", `${outdir}/index.html`);
    fs.writeFileSync(`${outdir}/mobile.css`, lowerCss(fs.readFileSync("src/mobile/mobile.css", "utf8")));
    fs.writeFileSync(`${outdir}/reading.css`, lowerCss(readingCss()));
  } else {
    for (const f of ["index.html", "styles.css"]) fs.copyFileSync(`src/${f}`, `${outdir}/${f}`);
  }
};
copyStatic();

const options = {
  entryPoints: { app: mobile ? "src/mobile/main.tsx" : "src/main.tsx" },
  outdir,
  bundle: true,
  format: "esm",
  platform: "browser",
  target: TARGET,
  jsx: "automatic",
  jsxImportSource: "preact",
  minify: prod,
  sourcemap: prod ? false : "linked",
  legalComments: "none",
  logLevel: "info",
  define: { "process.env.NODE_ENV": JSON.stringify(prod ? "production" : "development") },
};

if (watch) {
  const ctx = await esbuild.context(options);
  await ctx.watch();
  const statics = mobile ? ["index.html", "mobile.css"] : ["index.html", "styles.css"];
  fs.watch(mobile ? "src/mobile" : "src", (_e, f) => { if (statics.includes(f)) copyStatic(); });
} else {
  await esbuild.build(options);
}
