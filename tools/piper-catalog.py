# Usage: python tools/piper-catalog.py src-tauri/src/piper_voices.rs
# Builds src-tauri/src/piper_voices.rs: the Piper voices Paginaut offers, pinned to one commit of
# rhasspy/piper-voices, with sizes and hashes (LFS sha256 for .onnx, git blob sha1 for .onnx.json).
import json, os, sys, urllib.request, urllib.parse, collections, hashlib

COMMIT = "c10ece1aade47bb51c153c893d14e5bf8e5b7117"
# Needs the Windows runtime unpacked in %TEMP%/claude/piper/rt (for its espeak-ng languages).
TMP = os.path.join(os.environ["TEMP"], "claude")
if not os.path.exists(os.path.join(TMP, "voices.json")):
    urllib.request.urlretrieve(f"https://huggingface.co/rhasspy/piper-voices/resolve/{COMMIT}/voices.json", os.path.join(TMP, "voices.json"))
voices = json.load(open(os.path.join(TMP, "voices.json"), encoding="utf-8"))
espeak = set()
for root, _, files in os.walk(os.path.join(TMP, "piper", "rt", "piper", "espeak-ng-data", "lang")):
    espeak.update(f.lower() for f in files)
DIPHTHONGS = {"aɪ", "aʊ", "ɔɪ", "eɪ", "oʊ"}
cache = os.path.join(TMP, "piper", "configs")
os.makedirs(cache, exist_ok=True)


def get(url):
    with urllib.request.urlopen(urllib.parse.quote(url, safe=":/")) as r:
        return r.read()


tree = {}
def listing(d):
    if d not in tree:
        tree[d] = json.loads(get(f"https://huggingface.co/api/models/rhasspy/piper-voices/tree/{COMMIT}/{d}"))
    return tree[d]


by = collections.defaultdict(list)
for k, x in voices.items():
    by[x["language"]["code"]].append(x)

RANK = {"x_low": 0, "low": 1, "medium": 2, "high": 3}
out = []
for code in sorted(by):
    vs = by[code]
    good = [x for x in vs if RANK[x["quality"]] >= 2]
    vs = good or vs
    for x in sorted(vs, key=lambda x: x["key"]):
        onnx = next(p for p in x["files"] if p.endswith(".onnx"))
        conf = onnx + ".json"
        cpath = os.path.join(cache, x["key"] + ".onnx.json")
        if not os.path.exists(cpath):
            open(cpath, "wb").write(get(f"https://huggingface.co/rhasspy/piper-voices/resolve/{COMMIT}/{conf}"))
        raw = open(cpath, "rb").read()
        c = json.loads(raw)
        why = None
        if c.get("phoneme_type", "espeak") != "espeak":
            why = "phonemes " + c.get("phoneme_type")
        elif c["espeak"]["voice"].lower() not in espeak:
            why = "espeak voice " + c["espeak"]["voice"]
        elif any(len(k) > 1 and k not in DIPHTHONGS for k in c["phoneme_id_map"]):
            why = "multi " + str([k for k in c["phoneme_id_map"] if len(k) > 1])
        if why:
            print("skip", x["key"], why, file=sys.stderr)
            continue
        entries = {e["path"]: e for e in listing(os.path.dirname(onnx))}
        e = entries[onnx]
        sha = e["lfs"]["oid"]
        size = e["lfs"]["size"]
        blob = hashlib.sha1(b"blob %d\0" % len(raw) + raw).hexdigest()
        assert blob == entries[conf]["oid"], x["key"]
        lang = c["language"]
        out.append((x["key"], urllib.parse.quote(onnx[: -len(".onnx")]), lang["name_english"], lang.get("country_english", ""), code.replace("_", "-"),
                    x["quality"], c.get("num_speakers", 1), size, sha, len(raw), blob))
        print(x["key"], file=sys.stderr)

rs = ["//! The Piper voices on offer (generated by tools/piper-catalog.py from rhasspy/piper-voices at one commit).",
      "//! Each: id, path in the repository (without .onnx, as in a URL), language, country, BCP-47 tag, quality,",
      "//! model size and SHA-256, config size and git blob SHA-1.", "",
      f'pub const COMMIT: &str = "{COMMIT}";', "",
      "pub struct Voice {", "    pub id: &'static str,", "    pub path: &'static str,", "    pub lang: &'static str,",
      "    pub country: &'static str,", "    pub tag: &'static str,", "    pub quality: &'static str,",
      "    pub model: (u64, &'static str),", "    pub config: (u64, &'static str),", "}", "",
      "pub const VOICES: &[Voice] = &["]
for (k, p, l, cty, tag, q, n, size, sha, csize, blob) in out:
    rs.append(f'    Voice {{ id: "{k}", path: "{p}", lang: "{l}", country: "{cty}", tag: "{tag}", quality: "{q}", model: ({size}, "{sha}"), config: ({csize}, "{blob}") }},')
rs.append("];")
open(sys.argv[1], "w", encoding="utf-8", newline="\n").write("\n".join(rs) + "\n")
print(len(out), "voices", file=sys.stderr)
