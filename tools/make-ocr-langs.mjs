async function tree(repo) {
  const res = await fetch(`https://api.github.com/repos/tesseract-ocr/${repo}/git/trees/${TAG}`, { headers: { "User-Agent": "paginaut-tools" } });
  if (!res.ok) throw new Error(`${repo}: HTTP ${res.status}`);
  const json = await res.json();
  return Object.fromEntries(json.tree.filter((e) => /^[a-z_]+\.traineddata$/.test(e.path)).map((e) => [e.path.replace(".traineddata", ""), e]));
}

const fast = await tree("tessdata_fast");
const best = await tree("tessdata_best");
const rows = [];
for (const [code, name] of Object.entries(NAMES)) {
  const f = fast[code], b = best[code];
  if (!f || !b) throw new Error(`missing ${code}`);
  rows.push(`    Lang { code: "${code}", name: "${name}", fast: (${f.size}, "${f.sha}"), best: (${b.size}, "${b.sha}") },`);
}
const missing = Object.keys(fast).filter((c) => !NAMES[c] && c !== "osd" && c !== "equ");
if (missing.length) console.warn("not offered (no name):", missing.join(" "));

const out = `// Generated by tools/make-ocr-langs.mjs from tesseract-ocr/tessdata_fast and
// tessdata_best at tag ${TAG}. Do not edit by hand.

/// Tesseract release tag the models come from.
pub const TAG: &str = "${TAG}";

pub struct Lang {
    pub code: &'static str,
    pub name: &'static str,
    /// Size in bytes and git blob SHA-1 of the fast and best models.
    pub fast: (u64, &'static str),
    pub best: (u64, &'static str),
}

pub const LANGS: &[Lang] = &[
${rows.join("\n")}
];
`;
const dest = path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..", "src-tauri", "src", "ocr_langs.rs");
fs.writeFileSync(dest, out);
console.log(`wrote ${rows.length} languages to ${dest}`);
